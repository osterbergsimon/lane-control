"""Where lane-control's generated coordination goes in a project (UP-5; the policy: orchestrators/README.md, "What
lane-control writes into a project").

The generated sections (project-setup's lane-control section, the native-orca adapter's section) live in their own
file, AGENTS.lane-control.md, at the repo root. AGENTS.md, which the project's people write, gets exactly one pointer
line to it and nothing else. Each section keeps its comment markers, so a re-run replaces it in place and never adds a
second one; a section found in AGENTS.md (from before this file existed) is moved out on the next run. Markers that
cannot be paired are refused, never guessed at. Text is handled as surrogate-escaped str, so any bytes survive.

project-setup and both adapters load this file by path (it has no imports of its own beyond the standard library).
"""
import os
import secrets
import stat
import subprocess
from pathlib import Path

GENERATED = "AGENTS.lane-control.md"
POINTER_MARK = "<!-- lane-control:pointer -->"
POINTER = (f"Agents run by lane-control also read `{GENERATED}`: the coordination lane-control generates for this "
           f"project (a re-run replaces it; do not edit it by hand). {POINTER_MARK}")
HEADER = (f"# {GENERATED}\n\nGenerated by lane-control (project-setup, scripts/orch): AGENTS.md points here. A re-run "
          "replaces each marked section in place; hand-written rules belong in AGENTS.md.\n")


def _nl(text: str) -> str:
    return "\r\n" if "\r\n" in text else "\n"


def split_block(text: str, begin: str, end: str):
    """(head, block, rest), or (text, None, None) when the block is absent; refuses markers it cannot pair."""
    if text.count(begin) != text.count(end) or text.count(begin) > 1 or (
            begin in text and text.index(end) < text.index(begin)):
        raise ValueError(f"unpaired, repeated or reversed {begin} markers; fix them by hand and run again")
    if begin not in text:
        return text, None, None
    head, rest = text.split(begin, 1)
    block, rest = rest.split(end, 1)
    return head, begin + block + end, rest


def put_block(text: str, block: str, begin: str, end: str) -> str:
    """text with `block`: an older copy replaced in place, else added at the end after a blank line."""
    head, old, rest = split_block(text, begin, end)
    nl = _nl(text)
    block = block.replace("\r\n", "\n").replace("\n", nl)
    if old is not None:
        return head + block + rest
    if not text:
        return block + nl
    return text + ("" if text.endswith("\n") else nl) + nl + block + nl


def drop_block(text: str, begin: str, end: str) -> str:
    """text minus the block and the blank line put before it; the text around it is left as it was."""
    head, old, rest = split_block(text, begin, end)
    if old is None:
        return text
    nl = _nl(text)
    rest = rest[len(nl):] if rest.startswith(nl) else rest[1:] if rest.startswith("\n") else rest
    if not head.strip():  # the block opened the file: the text after it does now, with no blank line first
        return rest.lstrip("\r\n")
    if not rest.strip():
        body = head.rstrip("\r\n")
        return body + nl if body else ""
    if head.endswith(nl + nl) and rest.startswith(nl):
        head = head[:-len(nl)]
    return head + rest


def _pointer_lines(text: str) -> list:
    lines = text.splitlines(keepends=True)
    return [i for i, line in enumerate(lines) if POINTER_MARK in line]


def with_pointer(text: str) -> str:
    """AGENTS.md text with exactly one pointer line: an older one replaced in place, else added at the end."""
    found = _pointer_lines(text)
    if len(found) > 1:
        raise ValueError(f"AGENTS.md has more than one {POINTER_MARK} line; keep one by hand and run again")
    nl = _nl(text)
    if found:
        lines = text.splitlines(keepends=True)
        ending = lines[found[0]][len(lines[found[0]].rstrip("\r\n")):]
        lines[found[0]] = POINTER + ending
        return "".join(lines)
    if not text:
        return POINTER + nl
    return text + ("" if text.endswith("\n") else nl) + nl + POINTER + nl


def without_pointer(text: str) -> str:
    """AGENTS.md text minus the pointer line and the blank line put before it."""
    found = _pointer_lines(text)
    if len(found) > 1:
        raise ValueError(f"AGENTS.md has more than one {POINTER_MARK} line; remove them by hand")
    if not found:
        return text
    lines = text.splitlines(keepends=True)
    i = found[0]
    del lines[i]
    if i == len(lines) and i > 0 and not lines[i - 1].strip():  # it was last: the blank line before it goes too
        del lines[i - 1]
    return "".join(lines)


def generated_base(text: str) -> str:
    """What the generated file starts from: its text, or the header for a new or empty file."""
    return text if text.strip() else HEADER


def holds_nothing(text: str) -> bool:
    """True when the generated file has no section left (only the header, or nothing): it can go, and its pointer."""
    return text.strip() in ("", HEADER.strip())


def replaced(text: str, new_block: str, begin: str, end: str):
    """The block in `text` when it differs from `new_block` (line endings aside), else None: what a rewrite would
    replace that lane-control did not write in this version (an older version, or a hand edit)."""
    old = split_block(text, begin, end)[1]
    if old is None or old.replace("\r\n", "\n") == new_block.replace("\r\n", "\n"):
        return None
    return old


def write_atomic(f: Path, text: str):
    """The whole file at once: written beside it, then renamed over it (keeps its mode; any bytes survive)."""
    tmp = f.with_name(f".{f.name}.{secrets.token_hex(4)}.tmp")
    try:
        tmp.write_bytes(text.encode(errors="surrogateescape"))
        if f.exists():
            os.chmod(tmp, stat.S_IMODE(f.stat().st_mode))
        os.replace(tmp, f)
    finally:
        tmp.unlink(missing_ok=True)


def ignored(repo: Path, name: str = GENERATED):
    """Where git ignores `name` in `repo` ("<file>:<line>:<pattern>"), or None (not ignored, tracked, or no repo)."""
    try:
        r = subprocess.run(["git", "-C", str(repo), "check-ignore", "-v", "--", name], capture_output=True, text=True,
                           timeout=30)
    except (OSError, subprocess.TimeoutExpired):
        return None
    return r.stdout.split("\t", 1)[0].strip() if r.returncode == 0 and r.stdout.strip() else None


def ignored_message(where: str) -> str:
    return (f"{GENERATED} is gitignored here ({where}), but lane-control commits it so that every lane worktree has "
            f"it: un-ignore it (a `!{GENERATED}` line after that rule) and run again. Nothing was changed")
